// @ts-check
/**
 * Generate the embedded skill bodies used by both the Host fallback and the
 * preset-scoped skill registration; `dsh/skills/` stays the authoring source
 * in the repository but is not required in an installed package.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const skillsDir = join(root, 'dsh', 'skills')
const outputFile = join(root, 'src', 'shared', 'skills.generated.ts')
const SKILL_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const OLD_CONTRACT = 'present, otherwise the bundled core pack at `../../../core/<file>` relative to\n> this skill.'
const NEW_CONTRACT = 'present, otherwise the bundled core pack at `core/<file>` relative to\n> the plugin package root.'

/**
 * Parse one `SKILL.md` into the embedded record.
 * @param {string} id - directory name, also the skill id.
 * @param {string} file - absolute `SKILL.md` path.
 */
function parseSkill(id, file) {
  if (!SKILL_ID.test(id)) throw new Error(`${id}: invalid skill id`)
  const raw = readFileSync(file, 'utf8')
  const match = /^---\r?\n([\s\S]*?)\r?\n---[ \t]*\r?\n?/.exec(raw)
  if (match === null) throw new Error(`${id}: missing frontmatter`)
  const frontmatter = match[1]

  const name = /^name:\s*(.+?)\s*$/m.exec(frontmatter)?.[1]
  if (name !== id) throw new Error(`${id}: frontmatter name is ${JSON.stringify(name)}`)

  const descriptionLiteral = /^description:\s*("(?:[^"\\]|\\.)*")\s*$/m.exec(frontmatter)?.[1]
  if (descriptionLiteral === undefined) throw new Error(`${id}: description must be one double-quoted line`)
  const description = JSON.parse(descriptionLiteral)
  if (typeof description !== 'string' || description === '') throw new Error(`${id}: empty description`)

  const userInvocable = /^user-invocable:\s*(true|false)\s*$/m.exec(frontmatter)?.[1] !== 'false'
  const modelInvocable = /^disable-model-invocation:\s*(true|false)\s*$/m.exec(frontmatter)?.[1] !== 'true'

  let content = raw.slice(match[0].length)
  if (!content.includes(OLD_CONTRACT)) {
    throw new Error(`${id}: path contract changed; update scripts/generate-skills.mjs`)
  }
  content = content.replace(OLD_CONTRACT, NEW_CONTRACT)
  if (content.includes('../../../core/')) throw new Error(`${id}: unresolved relative core path`)
  if (content.trim() === '') throw new Error(`${id}: empty skill body`)

  return { name, description, content, userInvocable, modelInvocable }
}

/**
 * Regenerate `src/shared/skills.generated.ts`.
 *
 * In a repository checkout the Markdown sources are read and the module is
 * rewritten. In an installed package the `dsh/skills` directory is absent, so
 * the committed generated module is kept and the build remains reproducible.
 * @returns {number} number of generated skills, or 0 when the source is absent.
 */
export function generateSkills() {
  if (!existsSync(skillsDir)) {
    if (!existsSync(outputFile)) {
      throw new Error('dsh/skills is absent and src/shared/skills.generated.ts is missing')
    }
    console.log('skills: dsh/skills absent; using the committed generated module')
    return 0
  }

  const entries = readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => parseSkill(entry.name, join(skillsDir, entry.name, 'SKILL.md')))
    .sort((left, right) => left.name.localeCompare(right.name))

  const body = [
    '// @generated by scripts/generate-skills.mjs — do not edit by hand.',
    '// Source: dsh/skills/<id>/SKILL.md. Regenerate with `npm run build`.',
    '',
    'export interface KazeSkillBody {',
    '  readonly name: string',
    '  readonly description: string',
    '  readonly content: string',
    '  readonly modelInvocable: boolean',
    '  readonly userInvocable: boolean',
    '}',
    '',
    'export const KAZE_SKILLS: readonly KazeSkillBody[] = [',
    ...entries.map((entry) => [
      '  {',
      `    name: ${JSON.stringify(entry.name)},`,
      `    description: ${JSON.stringify(entry.description)},`,
      `    content: ${JSON.stringify(entry.content)},`,
      `    modelInvocable: ${entry.modelInvocable},`,
      `    userInvocable: ${entry.userInvocable},`,
      '  },',
    ].join('\n')),
    ']',
    '',
    'export const KAZE_SKILL_BY_ID: ReadonlyMap<string, KazeSkillBody> = new Map(',
    '  KAZE_SKILLS.map((skill) => [skill.name, skill]),',
    ')',
    '',
  ].join('\n')

  const previous = existsSync(outputFile) ? readFileSync(outputFile, 'utf8') : ''
  if (previous !== body) writeFileSync(outputFile, body, 'utf8')
  console.log(`skills: generated ${entries.length} embedded skill bodies`)
  return entries.length
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateSkills()
}
